import { mkdir, readdir, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const publicRoot = path.resolve("public");
const optimizedRoot = path.join(publicRoot, "optimized");

await mkdir(optimizedRoot, { recursive: true });
await mkdir(path.join(publicRoot, "projects", "thumbnails", "mobile"), { recursive: true });

const outputs = [];

async function webp(source, destination, options = {}) {
  const input = path.join(publicRoot, source);
  const output = path.join(publicRoot, destination);
  await mkdir(path.dirname(output), { recursive: true });
  let pipeline = sharp(input).rotate();
  if (options.width) pipeline = pipeline.resize({ width: options.width, withoutEnlargement: true });
  await pipeline
    .webp({
      quality: options.quality ?? 80,
      lossless: options.lossless ?? false,
      alphaQuality: 92,
      effort: 6,
      smartSubsample: true,
    })
    .toFile(output);
  const [before, after] = await Promise.all([stat(input), stat(output)]);
  outputs.push({ source, destination, before: before.size, after: after.size });
}

for (const width of [480, 768, 1023]) {
  await webp("grethiel-images/grethiel-joy.png", `optimized/grethiel-joy-${width}.webp`, { width, quality: 80 });
  await webp("grethiel-images/joy-grethiel.png", `optimized/joy-grethiel-${width}.webp`, { width, quality: 80 });
}

await webp("grethiel-images/grethiel-joy.png", "optimized/grethiel-avatar-128.webp", { width: 128, quality: 82 });
await webp("grethiel-joy-logo.png", "optimized/grethiel-joy-logo-640.webp", { width: 640, lossless: true });
await webp("grethiel-joy-logo-white.png", "optimized/grethiel-joy-logo-white-960.webp", { width: 960, lossless: true });
await webp("gj-mobile-icon.png", "optimized/gj-mobile-icon-192.webp", { width: 192, lossless: true });
await webp("home-intro-background.png", "optimized/home-intro-background-800.webp", { width: 800, quality: 74 });
await webp("home-intro-background.png", "optimized/home-intro-background-1672.webp", { width: 1672, quality: 74 });
await webp("about-story-bg.png", "optimized/about-story-bg-800.webp", { width: 800, quality: 74 });
await webp("about-story-bg.png", "optimized/about-story-bg-2039.webp", { width: 2039, quality: 74 });

await sharp(path.join(publicRoot, "gj-favicon.png"))
  .resize(64, 64, { fit: "cover" })
  .png({ compressionLevel: 9, palette: true, quality: 90 })
  .toFile(path.join(optimizedRoot, "gj-favicon-64.png"));

for (const file of await readdir(path.join(publicRoot, "projects", "thumbnails"))) {
  if (!file.endsWith(".webp")) continue;
  await webp(
    path.posix.join("projects", "thumbnails", file),
    path.posix.join("projects", "thumbnails", "mobile", file),
    { width: 400, quality: 76 },
  );
}

await webp("projects/direct-construction.png", "projects/direct-construction.webp", { width: 1920, quality: 80 });
await webp("projects/tradie.png", "projects/tradie-growth.webp", { width: 1920, quality: 80 });
await webp("projects/life-regeneration-church.png", "projects/life-regeneration-church.webp", { width: 1920, quality: 82 });

const before = outputs.reduce((total, item) => total + item.before, 0);
const after = outputs.reduce((total, item) => total + item.after, 0);
console.log(`Generated ${outputs.length + 1} optimized images.`);
console.log(`Referenced source bytes: ${(before / 1024 / 1024).toFixed(2)} MB`);
console.log(`Generated bytes: ${(after / 1024 / 1024).toFixed(2)} MB plus favicon`);
